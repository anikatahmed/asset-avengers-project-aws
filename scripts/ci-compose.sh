#!/usr/bin/env bash
# A CI-only entry point: every operation names one standalone Compose file/project.
# No Docker daemon-wide cleanup or development Compose fallback is permitted.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CI_COMPOSE_FILE="$ROOT/deployment/ci/ci.compose.yml"
ACTION="${1:-}"
if [[ "$ACTION" == new-project ]]; then
  # Random suffix also distinguishes jobs, branches, retries and Jenkins agents.
  suffix="$(od -An -N8 -tx1 /dev/urandom | tr -d ' \n')"
  printf 'endgame-ci-%s\n' "$suffix"
  exit 0
fi
if [[ ! "${CI_PROJECT_NAME:-}" =~ ^endgame-ci-[a-f0-9]{16}$ ]]; then
  echo 'CI_PROJECT_NAME must be a name generated by: bash scripts/ci-compose.sh new-project' >&2
  exit 1
fi
STATE_DIR="$ROOT/.ci"
RECEIPT="$STATE_DIR/$CI_PROJECT_NAME.initialized"
# Normal Jenkins runs use the root .env; isolated verification may supply a temp fixture.
ENV_FILE="${CI_ENV_FILE:-$ROOT/.env}"
COMPOSE=(docker compose --env-file "$ENV_FILE" -p "$CI_PROJECT_NAME" -f "$CI_COMPOSE_FILE")
if [[ "$ACTION" == init ]]; then
  [[ $# -eq 1 ]] || { echo 'init takes no additional arguments' >&2; exit 1; }
  [[ -f "$ENV_FILE" ]] || { echo 'Missing CI environment file' >&2; exit 1; }
  # Do not arm cleanup on an invalid configuration. This does not create Docker resources.
  "${COMPOSE[@]}" config >/dev/null
  mkdir -p "$STATE_DIR"
  (umask 077; printf '%s\n' "$CI_PROJECT_NAME" > "$RECEIPT")
  echo "Initialized isolated CI project: $CI_PROJECT_NAME"
  exit 0
fi
if [[ ! -f "$RECEIPT" || "$(cat "$RECEIPT")" != "$CI_PROJECT_NAME" ]]; then
  echo 'CI project was not initialized in this workspace; refusing Docker operation.' >&2
  exit 1
fi
if [[ "$ACTION" == cleanup ]]; then
  [[ $# -eq 1 ]] || { echo 'cleanup takes no additional arguments' >&2; exit 1; }
  echo "Removing only temporary CI project: $CI_PROJECT_NAME"
  "${COMPOSE[@]}" down --volumes --remove-orphans
  rm -f "$RECEIPT"
  exit 0
fi
case "$ACTION" in
  up|build|ps|logs|exec|config) "${COMPOSE[@]}" "$@" ;;
  *) echo 'Usage: ci-compose.sh new-project|init|up|build|ps|logs|exec|config|cleanup' >&2; exit 1 ;;
esac
